#!/usr/bin/env python3
"""Generate the compiled locale table from locales/<BCP-47>/strings.json."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
locale_dirs = sorted(path for path in (ROOT / "locales").iterdir() if path.is_dir() and (path / "strings.json").is_file())
if not any(path.name == "en-US" for path in locale_dirs):
    raise SystemExit("locales/en-US/strings.json is required as the fallback locale")
files = {}
for path in locale_dirs:
    if not re.fullmatch(r"[A-Za-z]{2,3}(?:-[A-Za-z0-9]{2,8})*", path.name):
        raise SystemExit(f"{path.name}: directory must use a BCP 47 locale tag")
    files[path.name] = json.loads((path / "strings.json").read_text(encoding="utf-8"))
keys = set(files["en-US"])
header = (ROOT / "src" / "text.hpp").read_text(encoding="utf-8")
declared = {key for key in re.findall(r"SPACEVIEWER_TEXT\((\w+)\)", header) if key != "key"}
if keys != declared:
    raise SystemExit(f"text.hpp key mismatch: missing={sorted(declared-keys)}, unused={sorted(keys-declared)}")
for locale, data in files.items():
    missing, extra = keys - set(data), set(data) - keys
    if missing or extra:
        raise SystemExit(f"{locale}: missing={sorted(missing)}, extra={sorted(extra)}")

def literal(value):
    return json.dumps(value, ensure_ascii=True)

lines = ["// Generated by tools/generate_locales.py. Do not edit by hand.", "#pragma once", "", "namespace zh {", "struct LocaleRow { const char* locale; const char* key; const char* value; };", "inline constexpr LocaleRow kLocaleRows[] = {"]
for locale, data in sorted(files.items()):
    for key, value in sorted(data.items()):
        lines.append(f"  {{{literal(locale)}, {literal(key)}, {literal(value)}}},")
lines += ["};", "}  // namespace zh", ""]
(ROOT / "src" / "locales_generated.hpp").write_text("\n".join(lines), encoding="utf-8")
